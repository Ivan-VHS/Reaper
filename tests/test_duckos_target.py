from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from reaper.native_compiler import NativeToolchainError, build_executable, compile_source

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "targets" / "duckos" / "boot_contract_v1.rpr"
EXPECTED = "0\n0\n-2\n-3\n-4\n-5\n-6\n-6\n-7\n"


class DuckOSTargetTests(unittest.TestCase):
    def test_boot_contract_source_is_in_the_checked_native_subset(self) -> None:
        source = SOURCE.read_text(encoding="utf-8")
        generated = compile_source(source, str(SOURCE))
        self.assertIn("Generated by Reaper AOT", generated)

    def test_reference_and_native_backends_match_the_boot_fixture_matrix(self) -> None:
        if not (shutil.which("cc") or shutil.which("clang") or shutil.which("gcc")):
            self.skipTest("GCC-compatible C compiler is not installed")

        reference = subprocess.run(
            [sys.executable, "-m", "reaper", str(SOURCE)],
            cwd=ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
            timeout=30,
            check=False,
        )
        self.assertEqual(reference.returncode, 0, reference.stderr)
        self.assertEqual(reference.stdout, EXPECTED)

        with tempfile.TemporaryDirectory(prefix="reaper-duckos-target-") as folder:
            executable = build_executable(
                SOURCE.read_text(encoding="utf-8"),
                Path(folder) / ("boot-contract.exe" if sys.platform == "win32" else "boot-contract"),
                filename=str(SOURCE),
                timeout=120,
            )
            native = subprocess.run(
                [str(executable)],
                cwd=ROOT,
                capture_output=True,
                text=True,
                encoding="utf-8",
                timeout=30,
                check=False,
            )
        self.assertEqual(native.returncode, 0, native.stderr)
        self.assertEqual(native.stdout, reference.stdout)
        self.assertEqual(native.stdout, EXPECTED)


if __name__ == "__main__":
    unittest.main()
