size_t reaper_glyph_count(void) { return sizeof glyph_tokens / sizeof glyph_tokens[0]; }

const char *reaper_glyph_at(size_t index) {
    return index < reaper_glyph_count() ? glyph_tokens[index] : NULL;
}

const char *reaper_glyph_match(const char *source, size_t *matched_length) {
    const char *best = NULL;
    size_t best_length = 0;
    if (matched_length) *matched_length = 0;
    if (!source) return NULL;
    for (size_t i = 0; i < reaper_glyph_count(); ++i) {
        size_t length = strlen(glyph_tokens[i]);
        if (length > best_length && strncmp(source, glyph_tokens[i], length) == 0) {
            best = glyph_tokens[i];
            best_length = length;
        }
    }
    if (matched_length) *matched_length = best_length;
    return best;
}
