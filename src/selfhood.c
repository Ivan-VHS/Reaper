size_t reaper_selfhood_count(void) {
    return sizeof entries / sizeof entries[0];
}

const ReaperSelfhoodEntry *reaper_selfhood_at(size_t index) {
    return index < reaper_selfhood_count() ? &entries[index] : NULL;
}

const ReaperSelfhoodEntry *reaper_selfhood_find(const char *identity) {
    if (identity == NULL) return NULL;
    for (size_t i = 0u; i < reaper_selfhood_count(); ++i) {
        if (strcmp(entries[i].identity, identity) == 0) return &entries[i];
    }
    return NULL;
}
