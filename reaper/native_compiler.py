"""A deliberately small, checked AOT backend for Reaper's scalar language core.

The reference interpreter remains authoritative for dynamic features.  This
backend compiles a documented, statically checked subset to portable C17 and
uses an installed C compiler for the final host executable.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .parser import Node, parse
from .syntax_profiles import supported_source_extensions


class NativeCompileError(ValueError):
    """A source-located diagnostic from the native subset compiler."""


class NativeToolchainError(RuntimeError):
    """The requested host C compiler could not produce the native program."""


_I64 = "i64"
_BOOL = "bool"
_STRING = "string"


@dataclass(slots=True)
class Symbol:
    source_name: str
    c_name: str
    type_name: str
    mutable: bool


@dataclass(slots=True)
class Scope:
    parent: "Scope | None" = None
    symbols: dict[str, Symbol] = field(default_factory=dict)

    def find(self, name: str) -> Symbol | None:
        scope: Scope | None = self
        while scope is not None:
            found = scope.symbols.get(name)
            if found is not None:
                return found
            scope = scope.parent
        return None

    def define(self, symbol: Symbol) -> bool:
        if symbol.source_name in self.symbols:
            return False
        self.symbols[symbol.source_name] = symbol
        return True


@dataclass(slots=True)
class FunctionInfo:
    source_name: str
    c_name: str
    parameters: tuple[str, ...]
    node: Node


class NativeCompiler:
    """Compile the Reaper scalar subset into deterministic C17 source."""

    def __init__(self, filename: str = "<memory>") -> None:
        self.filename = filename
        self.global_scope = Scope()
        self.function_table: dict[str, FunctionInfo] = {}
        self.function_declarations: list[str] = []
        self.function_definitions: list[str] = []
        self.global_declarations: list[str] = []
        self.main_body: list[str] = []
        self._symbol_counter = 0
        self._function_counter = 0
        self._indent = 1
        self._inside_function = False
        self._current_function: str | None = None
        self._available_functions: set[str] = set()

    def _fail(self, node: Node | None, message: str) -> None:
        token = getattr(node, "token", None)
        line = getattr(token, "line", 1)
        column = getattr(token, "column", 1)
        raise NativeCompileError(
            f"{self.filename}:{line}:{column}: native compile error: {message}"
        )

    def _name(self, prefix: str) -> str:
        self._symbol_counter += 1
        return f"rpr_{prefix}_{self._symbol_counter}"

    @staticmethod
    def _children(node: Node) -> list[Node]:
        return node.children or []

    @staticmethod
    def _quote_c_string(value: str) -> str:
        # Octal escapes avoid the variable-length parsing rules of hexadecimal
        # escapes and preserve UTF-8 bytes independently of source characters.
        encoded = value.encode("utf-8")
        return '"' + "".join(f"\\{byte:03o}" for byte in encoded) + '"'

    def compile(self, program: Node) -> str:
        if program.kind != "program":
            self._fail(program, "expected a parsed program")
        for statement in self._children(program):
            self._compile_top_level(statement)

        prototypes = "\n".join(self.function_declarations)
        functions = "\n\n".join(self.function_definitions)
        globals_text = "\n".join(self.global_declarations)
        main_text = "\n".join(self.main_body)
        return f'''/* Generated by Reaper AOT. Do not edit this file by hand. */
#include <inttypes.h>
#include <limits.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static uint64_t rpr_steps = 0;
static unsigned rpr_call_depth = 0;
static int rpr_failed = 0;

static inline int64_t rpr_fail(const char *message) {{
    if (!rpr_failed) fprintf(stderr, "reaper native runtime: %s\\n", message);
    rpr_failed = 1;
    return 0;
}}

static inline int rpr_tick(void) {{
    if (++rpr_steps > UINT64_C(1000000)) {{
        (void)rpr_fail("execution step limit exceeded");
        return 0;
    }}
    return !rpr_failed;
}}

static inline int rpr_truthy(int64_t value) {{ return value != 0; }}

static inline int64_t rpr_add(int64_t a, int64_t b) {{
    if ((b > 0 && a > INT64_MAX - b) || (b < 0 && a < INT64_MIN - b))
        return rpr_fail("signed integer overflow in addition");
    return a + b;
}}

static inline int64_t rpr_sub(int64_t a, int64_t b) {{
    if ((b < 0 && a > INT64_MAX + b) || (b > 0 && a < INT64_MIN + b))
        return rpr_fail("signed integer overflow in subtraction");
    return a - b;
}}

static inline int64_t rpr_mul(int64_t a, int64_t b) {{
    if (a == 0 || b == 0) return 0;
    if ((a == -1 && b == INT64_MIN) || (b == -1 && a == INT64_MIN))
        return rpr_fail("signed integer overflow in multiplication");
    if (a > 0) {{
        if ((b > 0 && a > INT64_MAX / b) || (b < 0 && b < INT64_MIN / a))
            return rpr_fail("signed integer overflow in multiplication");
    }} else {{
        if ((b > 0 && a < INT64_MIN / b) || (b < 0 && a < INT64_MAX / b))
            return rpr_fail("signed integer overflow in multiplication");
    }}
    return a * b;
}}

static inline int64_t rpr_floor_div(int64_t a, int64_t b) {{
    if (b == 0) return rpr_fail("division by zero");
    if (a == INT64_MIN && b == -1) return rpr_fail("signed integer overflow in division");
    int64_t quotient = a / b;
    int64_t remainder = a % b;
    if (remainder != 0 && ((remainder < 0) != (b < 0))) --quotient;
    return quotient;
}}

static inline int64_t rpr_mod(int64_t a, int64_t b) {{
    if (b == 0) return rpr_fail("remainder by zero");
    if (a == INT64_MIN && b == -1) return 0;
    int64_t remainder = a % b;
    if (remainder != 0 && ((remainder < 0) != (b < 0))) remainder += b;
    return remainder;
}}

static inline int64_t rpr_pow(int64_t base, int64_t exponent) {{
    if (exponent < 0) return rpr_fail("negative exponent is not supported for i64");
    int64_t result = 1;
    while (exponent != 0 && !rpr_failed) {{
        if ((exponent & 1) != 0) result = rpr_mul(result, base);
        exponent >>= 1;
        if (exponent != 0) base = rpr_mul(base, base);
    }}
    return result;
}}

{globals_text}

{prototypes}

{functions}

int main(void) {{
    (void)rpr_call_depth;
{main_text}
    return rpr_failed ? EXIT_FAILURE : EXIT_SUCCESS;
}}
'''

    def _compile_top_level(self, node: Node) -> None:
        kind = node.kind
        if kind == "function":
            self._compile_function(node)
            return
        if kind == "declare":
            self._compile_declaration(node, self.global_scope, self.main_body, global_scope=True)
            return
        if kind == "change":
            self._compile_change(node, self.global_scope, self.main_body)
            return
        if kind in {"emit", "when", "while", "expression"}:
            self._compile_statement(node, self.global_scope, self.main_body)
            return
        if kind == "yield":
            self._fail(node, "'yield' is only valid inside a craft function")
        self._fail(node, f"'{kind}' is outside the native scalar subset")

    def _compile_function(self, node: Node) -> None:
        body = self._children(node)[0] if self._children(node) else None
        if body is None or not self._returns_on_all_paths(body):
            self._fail(node, "native craft functions must yield on every control-flow path")
        if self._inside_function:
            self._fail(node, "nested craft declarations are not supported by the native backend")
        if not isinstance(node.value, tuple) or len(node.value) != 2:
            self._fail(node, "malformed craft declaration")
        source_name, raw_parameters = node.value
        if not isinstance(source_name, str) or not isinstance(raw_parameters, list):
            self._fail(node, "malformed craft signature")
        if source_name in self.function_table or self.global_scope.find(source_name) is not None:
            self._fail(node, f"'{source_name}' is already declared")
        if len(raw_parameters) != len(set(raw_parameters)):
            self._fail(node, f"function '{source_name}' has duplicate parameter names")
        if len(self._children(node)) != 1:
            self._fail(node, "craft requires exactly one body block")

        c_name = f"rpr_fn_{self._function_counter}"
        self._function_counter += 1
        info = FunctionInfo(source_name, c_name, tuple(raw_parameters), node)
        # Register before checking the body so direct recursion works. Only
        # functions already encountered in the source are visible to calls.
        self.function_table[source_name] = info
        self._available_functions.add(source_name)
        parameter_names: list[str] = []
        function_scope = Scope(self.global_scope)
        for parameter in raw_parameters:
            c_parameter = self._name("arg")
            parameter_names.append(c_parameter)
            if not function_scope.define(Symbol(parameter, c_parameter, _I64, False)):
                self._fail(node, f"duplicate parameter '{parameter}'")

        signature = ", ".join(f"int64_t {name}" for name in parameter_names) or "void"
        call_arguments = ", ".join(parameter_names)
        prototype = f"static inline int64_t {c_name}({signature});"
        implementation_name = c_name + "_impl"
        implementation_prototype = f"static inline int64_t {implementation_name}({signature});"
        self.function_declarations.extend([prototype, implementation_prototype])

        previous_inside = self._inside_function
        previous_function = self._current_function
        previous_indent = self._indent
        self._inside_function = True
        self._current_function = source_name
        self._indent = 1
        body_lines: list[str] = []
        body = self._children(node)[0]
        self._compile_block(body, function_scope, body_lines, create_scope=False)
        body_text = "\n".join(body_lines)
        wrapper_arguments = call_arguments
        wrapper = f'''static inline int64_t {c_name}({signature}) {{
    if (rpr_call_depth >= 256U) return rpr_fail("call-depth limit exceeded");
    ++rpr_call_depth;
    int64_t result = {implementation_name}({wrapper_arguments});
    --rpr_call_depth;
    return result;
}}'''
        implementation = f'''static inline int64_t {implementation_name}({signature}) {{
{body_text}
    return 0;
}}'''
        self.function_definitions.append(wrapper + "\n\n" + implementation)
        self._inside_function = previous_inside
        self._current_function = previous_function
        self._indent = previous_indent

    @classmethod
    def _returns_on_all_paths(cls, block: Node) -> bool:
        if block.kind != "block":
            return False
        for statement in cls._children(block):
            if statement.kind == "yield":
                return True
            if statement.kind == "when":
                branches = cls._children(statement)
                if (
                    len(branches) == 3
                    and cls._returns_on_all_paths(branches[1])
                    and cls._returns_on_all_paths(branches[2])
                ):
                    return True
            if statement.kind == "block" and cls._returns_on_all_paths(statement):
                return True
        return False

    def _compile_statement(self, node: Node, scope: Scope, output: list[str]) -> None:
        kind = node.kind
        if kind == "block":
            self._compile_block(node, scope, output)
            return
        if kind == "declare":
            self._compile_declaration(node, scope, output, global_scope=False)
            return
        if kind == "change":
            self._compile_change(node, scope, output)
            return
        if kind == "emit":
            if self._inside_function:
                self._fail(node, "native craft functions cannot emit output; keep functions side-effect free")
            children = self._children(node)
            if len(children) != 1:
                self._fail(node, "emit requires one expression")
            expression, type_name = self._compile_expression(children[0], scope)
            output.append(self._line("if (!rpr_tick()) return EXIT_FAILURE;"))
            temporary = self._name("emit")
            if type_name == _STRING:
                output.append(self._line(f"const char *{temporary} = {expression};"))
                output.append(self._line("if (rpr_failed) return EXIT_FAILURE;"))
                output.append(self._line(f"(void)printf(\"%s\\n\", {temporary});"))
            elif type_name == _BOOL:
                output.append(self._line(f"int64_t {temporary} = (int64_t)({expression});"))
                output.append(self._line("if (rpr_failed) return EXIT_FAILURE;"))
                output.append(self._line(f"(void)printf(\"%s\\n\", rpr_truthy({temporary}) ? \"true\" : \"false\");"))
            else:
                output.append(self._line(f"int64_t {temporary} = (int64_t)({expression});"))
                output.append(self._line("if (rpr_failed) return EXIT_FAILURE;"))
                output.append(self._line(f"(void)printf(\"%\" PRId64 \"\\n\", {temporary});"))
            return
        if kind == "yield":
            if not self._inside_function:
                self._fail(node, "'yield' is only valid inside a craft function")
            children = self._children(node)
            if len(children) > 1:
                self._fail(node, "yield accepts at most one expression")
            if len(children) != 1:
                self._fail(node, "native craft functions must yield one integer expression")
            expression, type_name = self._compile_expression(children[0], scope)
            if type_name != _I64:
                self._fail(node, "native craft functions must yield an integer")
            output.append(self._line(f"return (int64_t)({expression});"))
            return
        if kind == "when":
            children = self._children(node)
            if len(children) not in {2, 3}:
                self._fail(node, "when requires a condition and one or two blocks")
            condition, condition_type = self._compile_expression(children[0], scope)
            self._require_condition(children[0], condition_type)
            tick = "if (!rpr_tick()) return 0;" if self._inside_function else "if (!rpr_tick()) return EXIT_FAILURE;"
            output.append(self._line(tick))
            output.append(self._line(f"if (rpr_truthy((int64_t)({condition}))) {{"))
            self._indent += 1
            self._compile_block(children[1], scope, output)
            self._indent -= 1
            if len(children) == 3:
                output.append(self._line("} else {"))
                self._indent += 1
                self._compile_block(children[2], scope, output)
                self._indent -= 1
            output.append(self._line("}"))
            return
        if kind == "while":
            children = self._children(node)
            if len(children) != 2:
                self._fail(node, "loop while requires a condition and body")
            condition, condition_type = self._compile_expression(children[0], scope)
            self._require_condition(children[0], condition_type)
            output.append(self._line(f"while (!rpr_failed && rpr_truthy((int64_t)({condition}))) {{"))
            self._indent += 1
            output.append(self._line("if (!rpr_tick()) break;"))
            self._compile_block(children[1], scope, output)
            self._indent -= 1
            output.append(self._line("}"))
            return
        if kind == "expression":
            children = self._children(node)
            if len(children) != 1:
                self._fail(node, "expression statement requires one expression")
            expression, _ = self._compile_expression(children[0], scope)
            tick = "if (!rpr_tick()) return 0;" if self._inside_function else "if (!rpr_tick()) return EXIT_FAILURE;"
            output.append(self._line(tick))
            output.append(self._line(f"(void)({expression});"))
            return
        if kind == "function":
            self._fail(node, "nested craft declarations are not supported by the native backend")
        self._fail(node, f"statement '{kind}' is outside the native scalar subset")

    def _compile_block(
        self,
        node: Node,
        parent: Scope,
        output: list[str],
        create_scope: bool = True,
    ) -> None:
        if node.kind != "block":
            self._fail(node, "expected a block")
        scope = Scope(parent) if create_scope else parent
        for statement in self._children(node):
            self._compile_statement(statement, scope, output)

    def _compile_declaration(
        self,
        node: Node,
        scope: Scope,
        output: list[str],
        *,
        global_scope: bool,
    ) -> None:
        if not isinstance(node.value, tuple) or len(node.value) != 2 or len(self._children(node)) != 1:
            self._fail(node, "malformed make/vary declaration")
        source_name, mutable = node.value
        if not isinstance(source_name, str) or not isinstance(mutable, bool):
            self._fail(node, "malformed declaration name or mutability")
        if global_scope and source_name in self.function_table:
            self._fail(node, f"'{source_name}' is already declared as a function")
        expression, type_name = self._compile_expression(self._children(node)[0], scope)
        if type_name not in {_I64, _BOOL, _STRING}:
            self._fail(node, "native variables must be i64, bool, or string")
        c_name = self._name("global" if global_scope else "local")
        symbol = Symbol(source_name, c_name, type_name, mutable)
        if not scope.define(symbol):
            self._fail(node, f"'{source_name}' is already declared in this scope")
        if global_scope:
            c_type = "const char *" if type_name == _STRING else "int64_t"
            self.global_declarations.append(f"static {c_type} {c_name};")
            output.append(self._line(f"{c_name} = {expression};"))
        else:
            c_type = "const char *" if type_name == _STRING else "int64_t"
            qualifier = "const " if not mutable and type_name != _STRING else ""
            const_pointer = " const" if not mutable and type_name == _STRING else ""
            output.append(self._line(f"{qualifier}{c_type}{const_pointer} {c_name} = {expression};"))

    def _compile_change(self, node: Node, scope: Scope, output: list[str]) -> None:
        if not isinstance(node.value, str) or len(self._children(node)) != 1:
            self._fail(node, "malformed change statement")
        symbol = scope.find(node.value)
        if symbol is None:
            self._fail(node, f"unknown name '{node.value}'")
        if not symbol.mutable:
            self._fail(node, f"'{node.value}' was declared with 'make' and cannot be changed; use 'vary'")
        if self._inside_function and any(
            symbol is global_symbol for global_symbol in self.global_scope.symbols.values()
        ):
            self._fail(node, "native craft functions cannot mutate global bindings")
        expression, type_name = self._compile_expression(self._children(node)[0], scope)
        if type_name != symbol.type_name:
            self._fail(node, f"cannot assign {type_name} to {symbol.type_name} variable '{node.value}'")
        tick = "if (!rpr_tick()) return 0;" if self._inside_function else "if (!rpr_tick()) return EXIT_FAILURE;"
        output.append(self._line(tick))
        output.append(self._line(f"{symbol.c_name} = {expression};"))

    def _compile_expression(self, node: Node, scope: Scope) -> tuple[str, str]:
        kind = node.kind
        if kind == "literal":
            value = node.value
            if isinstance(value, bool):
                return ("INT64_C(1)" if value else "INT64_C(0)"), _BOOL
            if isinstance(value, int):
                if value < -(1 << 63) or value > (1 << 63) - 1:
                    self._fail(node, "integer literal is outside signed i64 range")
                if value == -(1 << 63):
                    return "INT64_MIN", _I64
                if value < 0:
                    return f"(-INT64_C({-value}))", _I64
                return f"INT64_C({value})", _I64
            if isinstance(value, str):
                return self._quote_c_string(value), _STRING
            self._fail(node, "native backend does not support decimal or nothing literals")
        if kind == "name":
            if not isinstance(node.value, str):
                self._fail(node, "malformed identifier")
            symbol = scope.find(node.value)
            if symbol is None:
                self._fail(node, f"unknown name '{node.value}'")
            return symbol.c_name, symbol.type_name
        if kind == "unary":
            children = self._children(node)
            if len(children) != 1:
                self._fail(node, "malformed unary expression")
            operator = str(node.value)
            operand = children[0]
            if operator in {"-", "MINUS"} and operand.kind == "literal" and operand.value == (1 << 63):
                return "INT64_MIN", _I64
            expression, type_name = self._compile_expression(operand, scope)
            if operator in {"-", "MINUS"}:
                self._require_type(node, type_name, _I64, "unary '-' requires an integer")
                return f"rpr_sub(INT64_C(0), (int64_t)({expression}))", _I64
            if operator in {"NOT", "not", "!"}:
                if type_name not in {_I64, _BOOL}:
                    self._fail(node, "'not' requires an integer or boolean")
                return f"(!rpr_truthy((int64_t)({expression})))", _BOOL
            self._fail(node, f"unary operator '{operator}' is not supported")
        if kind == "binary":
            children = self._children(node)
            if len(children) != 2:
                self._fail(node, "malformed binary expression")
            left, left_type = self._compile_expression(children[0], scope)
            right, right_type = self._compile_expression(children[1], scope)
            operator = str(node.value)
            if operator in {"AND", "OR"}:
                if left_type not in {_I64, _BOOL} or right_type not in {_I64, _BOOL}:
                    self._fail(node, f"'{operator.lower()}' requires integer or boolean operands")
                c_operator = "&&" if operator == "AND" else "||"
                return f"(rpr_truthy((int64_t)({left})) {c_operator} rpr_truthy((int64_t)({right})))", _BOOL
            if operator in {"==", "!="} and left_type == right_type == _STRING:
                comparison = "== 0" if operator == "==" else "!= 0"
                return f"(strcmp({left}, {right}) {comparison})", _BOOL
            if operator in {"==", "!="} and left_type == right_type and left_type in {_I64, _BOOL}:
                return f"(({left}) {operator} ({right}))", _BOOL
            if operator in {"<", "<=", ">", ">="}:
                if left_type != _I64 or right_type != _I64:
                    self._fail(node, f"operator '{operator}' requires integer operands")
                return f"(({left}) {operator} ({right}))", _BOOL
            if operator in {"+", "-", "*", "//", "%", "**"}:
                self._require_type(node, left_type, _I64, f"operator '{operator}' requires integer operands")
                self._require_type(node, right_type, _I64, f"operator '{operator}' requires integer operands")
                helper = {
                    "+": "rpr_add", "-": "rpr_sub", "*": "rpr_mul",
                    "//": "rpr_floor_div", "%": "rpr_mod", "**": "rpr_pow",
                }[operator]
                return f"{helper}((int64_t)({left}), (int64_t)({right}))", _I64
            self._fail(node, f"binary operator '{operator}' is outside the native scalar subset")
        if kind == "call":
            children = self._children(node)
            if not children or children[0].kind != "name":
                self._fail(node, "native calls require a named craft function")
            function_name = children[0].value
            info = self.function_table.get(function_name)
            if scope.find(function_name) is not None:
                self._fail(node, f"'{function_name}' is a variable, not a function")
            if function_name not in self._available_functions or info is None:
                self._fail(node, f"function '{function_name}' is not declared at this point")
            arguments = children[1:]
            if len(arguments) != len(info.parameters):
                self._fail(node, f"{function_name}() expects {len(info.parameters)} arguments, got {len(arguments)}")
            rendered: list[str] = []
            for argument in arguments:
                expression, type_name = self._compile_expression(argument, scope)
                if type_name != _I64:
                    self._fail(argument, f"arguments to '{function_name}' must be integers")
                rendered.append(expression)
            return f"{info.c_name}({', '.join(rendered)})", _I64
        self._fail(node, f"expression '{kind}' is outside the native scalar subset")

    def _require_condition(self, node: Node, type_name: str) -> None:
        if type_name not in {_I64, _BOOL}:
            self._fail(node, "condition must be an integer or boolean")

    def _require_type(self, node: Node, actual: str, expected: str, message: str) -> None:
        if actual != expected:
            self._fail(node, message)

    def _line(self, text: str) -> str:
        return "    " * self._indent + text


def compile_ast(program: Node, filename: str = "<memory>") -> str:
    """Compile an already parsed AST to deterministic, portable C17 source."""
    return NativeCompiler(filename).compile(program)


def compile_source(
    source: str,
    filename: str = "<memory>",
    syntax: str | None = None,
) -> str:
    """Parse the selected surface syntax and compile the supported subset to C17."""
    return compile_ast(parse(source, filename, syntax=syntax), filename)


def find_c_compiler(explicit: str | None = None) -> str:
    """Find a GCC/Clang-compatible C compiler without invoking a shell."""
    requested = explicit or os.environ.get("CC")
    candidates = [requested] if requested else ["cc", "clang", "gcc"]
    for candidate in candidates:
        if candidate and shutil.which(candidate):
            return candidate
    raise NativeToolchainError(
        "no GCC/Clang-compatible C compiler found; install clang or GCC, or use --emit-c"
    )


def build_executable(
    source: str,
    output: str | Path,
    *,
    filename: str = "<memory>",
    compiler: str | None = None,
    optimization: str = "2",
    timeout: float = 120.0,
    syntax: str | None = None,
) -> Path:
    """Build a native host executable through a local C17 compiler.

    The compiler is invoked as an argument vector (never through a shell).
    The generated C file lives in a private temporary directory and is removed
    after the build. The caller chooses the executable destination explicitly.
    """
    if optimization not in {"0", "1", "2", "3", "s"}:
        raise ValueError("optimization must be one of 0, 1, 2, 3, or s")
    cc = find_c_compiler(compiler)
    destination = Path(output).expanduser().resolve()
    if filename != "<memory>" and destination == Path(filename).expanduser().resolve():
        raise ValueError("native output must not overwrite its Reaper source file")
    if destination.suffix.casefold() in {".c", ".h"} | supported_source_extensions():
        raise ValueError("native output must be an executable path, not a Reaper source or C header/source path")
    destination.parent.mkdir(parents=True, exist_ok=True)
    generated = compile_source(source, filename, syntax=syntax)
    # Build beside the requested output so the final replacement is atomic and
    # a failed compiler invocation never destroys a previously working binary.
    with tempfile.TemporaryDirectory(prefix=".reaper-aot-", dir=destination.parent) as temporary:
        temporary_root = Path(temporary)
        c_file = temporary_root / "program.c"
        temporary_executable = temporary_root / ("program.exe" if os.name == "nt" else "program")
        c_file.write_text(generated, encoding="utf-8", newline="\n")
        command = [cc, "-std=c17", f"-O{optimization}", "-Wall", "-Wextra", "-Wpedantic", str(c_file), "-o", str(temporary_executable)]
        try:
            result = subprocess.run(
                command,
                capture_output=True,
                text=True,
                check=False,
                timeout=timeout,
            )
        except subprocess.TimeoutExpired as error:
            raise NativeToolchainError(f"C compiler exceeded the {timeout:g}-second build limit") from error
        if result.returncode != 0:
            details = result.stderr.strip() or result.stdout.strip() or "compiler returned a non-zero status"
            raise NativeToolchainError(f"C compiler failed:\n{details}")
        if not temporary_executable.is_file():
            raise NativeToolchainError("C compiler reported success but did not create an executable")
        temporary_executable.replace(destination)
    return destination
