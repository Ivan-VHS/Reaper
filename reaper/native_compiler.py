def compile_ast(program: Node, filename: str = "<memory>") -> str:
    """Compile an already parsed AST to deterministic, portable C17 source."""
    return NativeCompiler(filename).compile(program)


def compile_source(source: str, filename: str = "<memory>") -> str:
    """Parse and compile a source string to C17."""
    return compile_ast(parse(source, filename), filename)


def find_c_compiler(explicit: str | None = None) -> str:
    """Find a GCC/Clang-compatible C compiler without invoking a shell."""
    requested = explicit or os.environ.get("CC")
    candidates = [requested] if requested else ["cc", "clang", "gcc"]
    for candidate in candidates:
        if candidate and shutil.which(candidate):
            return candidate
    raise NativeToolchainError(
        "no GCC/Clang-compatible C compiler found; install clang or GCC, or use --emit-c"
    )


def build_executable(
    source: str,
    output: str | Path,
    *,
    filename: str = "<memory>",
    compiler: str | None = None,
    optimization: str = "2",
    timeout: float = 120.0,
) -> Path:
    """Build a native host executable through a local C17 compiler.

    The compiler is invoked as an argument vector (never through a shell).
    The generated C file lives in a private temporary directory and is removed
    after the build. The caller chooses the executable destination explicitly.
    """
    if optimization not in {"0", "1", "2", "3", "s"}:
        raise ValueError("optimization must be one of 0, 1, 2, 3, or s")
    cc = find_c_compiler(compiler)
    destination = Path(output).expanduser().resolve()
    if filename != "<memory>" and destination == Path(filename).expanduser().resolve():
        raise ValueError("native output must not overwrite its Reaper source file")
    if destination.suffix.lower() in {".c", ".h", ".rpr"}:
        raise ValueError("native output must be an executable path, not a source-file path")
    destination.parent.mkdir(parents=True, exist_ok=True)
    generated = compile_source(source, filename)
    # Build beside the requested output so the final replacement is atomic and
    # a failed compiler invocation never destroys a previously working binary.
    with tempfile.TemporaryDirectory(prefix=".reaper-aot-", dir=destination.parent) as temporary:
        temporary_root = Path(temporary)
        c_file = temporary_root / "program.c"
        temporary_executable = temporary_root / ("program.exe" if os.name == "nt" else "program")
        c_file.write_text(generated, encoding="utf-8", newline="\n")
        command = [cc, "-std=c17", f"-O{optimization}", "-Wall", "-Wextra", "-Wpedantic", str(c_file), "-o", str(temporary_executable)]
        try:
            result = subprocess.run(
                command,
                capture_output=True,
                text=True,
                check=False,
                timeout=timeout,
            )
        except subprocess.TimeoutExpired as error:
            raise NativeToolchainError(f"C compiler exceeded the {timeout:g}-second build limit") from error
        if result.returncode != 0:
            details = result.stderr.strip() or result.stdout.strip() or "compiler returned a non-zero status"
            raise NativeToolchainError(f"C compiler failed:\n{details}")
        if not temporary_executable.is_file():
            raise NativeToolchainError("C compiler reported success but did not create an executable")
        temporary_executable.replace(destination)
    return destination
